def r3(fname, de):
    out = []
    for l in open(os.path.join(C.R3, fname), encoding="utf-8"):
        m = R3LINE.match(l)
        if m and abs(float(m.group(4)) - de) < 1e-12 * max(1, de):
            out.append(m)
    seen, uniq = set(), []
    for m in out:                        # some files repeat a block; keep the first occurrence per n
        if m.group(2) not in seen:
            seen.add(m.group(2))
            uniq.append(m)
    return uniq


