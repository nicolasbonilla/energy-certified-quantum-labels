def f_md(x, d=4):
    """the deposited table's own number format (map/code/tables_map.py), used only for the cross-check"""
    if x is None:
        return "—"
    if abs(x) >= 1000 or (abs(x) < 1e-3 and x != 0):
        return "%.2e" % x
    return ("%." + str(d) + "f") % x


def map_rows(S, n):
    return [r for lab in ORDER for r in sorted((r for r in S["rows"] if r["n"] == n and r["label"] == lab),
                                               key=lambda r: r["Jz"])]


def check_map_md(S):
    """every cell of the deposited Markdown map tables equals the JSON value in the deposited format"""
    nck = nbad = 0
    for n in (57, 115):
        md = md_table(SRC_MAPMD, "n = %d" % n)[1:]
        js = map_rows(S, n)
        assert len(md) == len(js), (n, len(md), len(js))
        for m, r in zip(md, js):
            exp = [LN_MD[r["label"]], "%.1f%s" % (r["Jz"], " (OOD)" if r.get("ood") else ""), f_md(r["O_GS"]),
                   f_md(r["eps"]["dig"]), f_md(r["at_lo"]["w_in"]), f_md(r["at_lo"]["w_pure"]),
                   f_md(r["at_up"]["w_out"]), f_md(r["at_dig"]["ratio_out"], 3)]
            exp += [f_md(r.get("f_in"), 3)]
            exp += [f_md(r["f_out"], 3) if r.get("f_out") is not None else "> " + f_md(r.get("f_out_lb"), 1)]
            exp += [f_md(r.get("law_ratio_out"), 3), f_md(r.get("eps_over_gap_in"), 3),
                    "%d+%d" % (r["n_points"]["+"], r["n_points"]["-"])]
