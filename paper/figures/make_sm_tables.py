def tex(s):
    """Plain LaTeX escaping of a short string (no institution names; Markdown bold removed)."""
    s = s.replace("**", "").replace("IBM's", "the dataset's").replace("IBM", "dataset")
    s = unicodedata.normalize("NFC", s)
    out, i = [], 0
    while i < len(s):
        ch = s[i]
        if i + 1 < len(s) and s[i + 1] == "̄":          # combining macron: C̄ -> \bar C
            out.append(r"$\bar{%s}$" % ch)
            i += 2
            continue
        if ch in UMAP:
            out.append(UMAP[ch])
        elif ch in "%&#":
            out.append(BS + ch)
        elif ch == "_":
            out.append(BS + "_")
        elif ch == "^":
            out.append(BS + "^{}")
        elif ch == "|":
            out.append("$|$")
        elif ch == "`":
            pass
        elif ord(ch) > 127:
            raise ValueError("unmapped character %r in %r" % (ch, s[:60]))
        else:
            out.append(ch)
        i += 1
    return "".join(out).replace("$$", "")


