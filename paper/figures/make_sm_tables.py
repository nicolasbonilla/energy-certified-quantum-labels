def prose(s):
    """Deposited prose cell -> LaTeX in the paper's notation (bond dimension spelled out, numbers typeset)."""
    s = s.replace("**", "").replace(r"\|", "|")
    s = re.sub(r"χ\s*=\s*(\d+) each", r"bond dimension \1 each", s)
    s = re.sub(r"χ\s*(\d+)\s*vs\s*χ\s*(\d+)", r"bond dimension \1 vs \2", s)
    s = re.sub(r"χ\s*(\d+)\s*→\s*(\d+)", r"bond dimension \1 → \2", s)
    s = re.sub(r"χ\s*≤\s*(\d+)", r"bond dimension ≤ \1", s)
    s = re.sub(r"([\d\]])\s+J\b", r"\1", s)                 # energies: units of the exchange coupling (caption)
    s = re.sub(r"(\d)-(\d)", r"\1–\2", s)                    # numeric ranges: en dash
    keep = []

    def protect(latex):
        keep.append(latex)
        return "\x00%d\x00" % (len(keep) - 1)
    s = re.sub(r"(\d+(?:\.\d+)?)e([+-]?)0*(\d+)",
               lambda m: protect(r"$%s\times10^{%s%s}$" % (m.group(1), "-" if m.group(2) == "-" else "",
                                                          m.group(3))), s)
    for a, b in PROSE:
        if a in s:
            s = s.replace(a, protect(b))
    s = tex(s)
    return re.sub("\x00(\\d+)\x00", lambda m: keep[int(m.group(1))], s).replace("$$", "")


# --------------------------------------------------------------------------------------------- number formatting
def sig(x, n=3):
    """x rounded to n significant digits, as a decimal string (no exponent); None -> None."""
    if x is None:
        return None
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    d = max(0, n - 1 - e)
    s = "%.*f" % (d, x)
    if float(s) != 0 and math.floor(math.log10(abs(float(s)))) > e:       # 9.996 -> 10.0, keep n digits
        s = "%.*f" % (max(0, n - 2 - e), x)
    return "0" + s[2:] if s.startswith("-0") and float(s) == 0 else s.lstrip("+")


NUM = re.compile(r"^(\$[<>]\$|\$\\le\$)?([+-]?)(\d+)(?:\.(\d*))?(\S*)$")


def align(cells):
    """Pad a column of numeric strings with invisible digits so that the decimal points line up in a c column.

    A cell may carry a prefix ($>$, $\\le$) or a suffix (footnote mark); None or non-numeric cells are centred."""
    parsed = [NUM.match(c) if c is not None else None for c in cells]
    nums = [p for p in parsed if p]
    if not nums:
        return [c if c is not None else "---" for c in cells]
    wi = max(len(p.group(3)) for p in nums)
    wf = max(len(p.group(4) or "") for p in nums)
    anyneg = any(p.group(2) == "-" for p in nums)
    anyplus = any(p.group(2) == "+" for p in nums)
    anypre = [p.group(1) for p in nums if p.group(1)]
    wsuf = max(len(p.group(5)) for p in nums)
    out = []
    for c, p in zip(cells, parsed):
        if c is None:
            out.append("---")
            continue
        if not p:
            out.append(c)
            continue
        pre, sgn, ip, fp, suf = p.group(1) or "", p.group(2), p.group(3), p.group(4) or "", p.group(5)
        s = ""
        if anypre:
            s += pre if pre else r"\phantom{%s}" % anypre[0]
        if anyneg or anyplus:
            s += ("$-$" if sgn == "-" else "$+$" if sgn == "+" else r"\phantom{$%s$}" % ("-" if anyneg else "+"))
        if len(ip) < wi:
            s += r"\phantom{%s}" % ("0" * (wi - len(ip)))
        s += ip
        if wf:
            s += ("." + fp) if p.group(4) is not None else ""
            pad = wf - len(fp) + (1 if p.group(4) is None else 0)
            if pad:
                s += r"\phantom{%s}" % (("." if p.group(4) is None else "") + "0" * (wf - len(fp)))
        if wsuf:
            s += r"\rlap{%s}" % suf if suf else ""
        out.append(s)
    return out


def grp(x):
    """integer with thin-space grouping: 361358 -> 361\\,358"""
    s = str(int(x))
    parts = []
    while len(s) > 3:
        parts.insert(0, s[-3:])
        s = s[:-3]
    parts.insert(0, s)
    return r"\,".join(parts)


def jz(x, ood=False):
    return ("%.1f" % x) + (r"\rlap{$^{\dagger}$}" if ood else "")


# ------------------------------------------------------------------------------------------------- table writer
def write(name, src, colspec, head, groups, note=None, tall=1):
    """groups: list of (heading or None, [rows]); a row is a list of cells, or (cells, 'cert') for a shaded row.
    head: list of header lines (already LaTeX, ending without \\\\)."""
    os.makedirs(OUT, exist_ok=True)
    ncol = len(colspec.replace("@{}", "").replace("@{\\hspace{1em}}", ""))
    # Page breaking: REVTeX 4.2f's output routine overfills by 1-4 pt the pages on which a longtable breaks by
    # itself.  So a long table is cut here into page-sized pieces at group boundaries; each piece is a longtable
    # that never breaks (\needspace moves it to a new page when the rest of the page is too short), and the pieces
    # after the first carry a "continued" line instead of a caption.
    pieces = pack(groups, CAP_FIRST, CAP_NEXT)
    for c in range(CAP_NEXT - 1, 19, -1):      # same number of pieces, more even lengths (no 3-row last page)
        p = pack(groups, min(CAP_FIRST, c), c)
        if len(p) == len(pieces):
            pieces = p
    L = ["%% generated by figures/make_sm_tables.py from %s -- do not edit" % src,
         r"{\footnotesize\setlength{\tabcolsep}{5pt}\renewcommand{\arraystretch}{1.3}"]
    for k, piece in enumerate(pieces):
        nlines = sum((g is not None) + len(rows) for g, rows in piece)
        L.append(r"\needspace{%dpt}" % (ROW_PT * tall * nlines + (CAPTION_PT if k == 0 else 0) + HEAD_PT * len(head)))
        if k == 0:                 # REVTeX's longtable steps the table counter: only the first piece is one
            L.append(r"\begin{longtable}{%s}" % colspec)
            L.append(r"\caption{\SMcap}\label{\SMlab}\\")
        else:
            L.append(r"\begin{center}\begin{tabular}{%s}" % colspec)
            L.append(r"\multicolumn{%d}{@{}l}{\textit{Table \thetable\ (continued)}}\\" % ncol)
        L += [r"\toprule"] + [hl(h) for h in head] + [r"\midrule"]
        for g, rows in piece:
            if g is not None:
                L.append(r"\multicolumn{%d}{@{}l}{\textbf{%s}}\\" % (ncol, g))
            for r in rows:
                shade = isinstance(r, tuple)
                cells = r[0] if shade else r
                assert len(cells) == ncol or (len(cells) == 1 and cells[0].startswith(r"\multicolumn")), (name, cells)
                if shade:          # certified row: coupling in bold (no colortbl: it loads the array package,
                    cells = [r"\textbf{%s}" % cells[0]] + cells[1:]     # which REVTeX 4.2f then breaks)
                L.append(" & ".join(cells) + r" \\")
        L.append(r"\bottomrule")
        if k < len(pieces) - 1:
            L.append(r"\multicolumn{%d}{r@{}}{\textit{continued on next page}}\\" % ncol)
        L.append(r"\end{longtable}" if k == 0 else r"\end{tabular}\end{center}")
    if note:
        L.append(r"\vspace{-6pt}\noindent{\scriptsize %s}\par\medskip" % note)
    L.append("}")
    with open(os.path.join(OUT, name + ".tex"), "w", encoding="utf-8") as fo:
        fo.write("\n".join(L) + "\n")
    print("wrote %-24s %3d rows, %d columns, %d piece(s)" % (name, sum(len(r) for _, r in groups), ncol, len(pieces)))


ROW_PT, HEAD_PT, CAPTION_PT = 13, 16, 110      # generous height estimates (pt) for \needspace
CAP_FIRST, CAP_NEXT = 30, 45                   # lines per piece: first piece (under its caption), later pieces


def pack(groups, cap1, capn):
    """split the row groups into pieces of at most cap lines (heading rows count); keep groups whole when possible,
    otherwise cut a group and repeat its heading with '(continued)'."""
    pieces, cur, used = [], [], 0
    cap = cap1
    for g, rows in groups:
        rows = list(rows)
        while rows:
            need = (g is not None) + len(rows)
            room = cap - used
            if need <= room:
                cur.append((g, rows))
                used += need
                rows = []
            elif used > 0 and (room < 8 or need <= 6):
                pieces.append(cur)                     # little room left, or a short group: start a new piece
                cur, used, cap = [], 0, capn
            else:                                      # cut the group
                take = room - (g is not None)
                if take < 3:                           # do not leave a tiny tail at the bottom
                    pieces.append(cur)
                    cur, used, cap = [], 0, capn
                    continue
                cur.append((g, rows[:take]))
                pieces.append(cur)
                cur, used, cap = [], 0, capn
                rows = rows[take:]
                g = (g + r" \textmd{\textit{(continued)}}") if g is not None and "(continued)" not in g else g
    if cur:
        pieces.append(cur)
    return pieces


def hl(h):
    """header line: end it with a row end unless it already carries one (followed by its cmidrules)"""
    return h if BS + "cmidrule" in h else h + r" \\"


def colgroups(cols):
    """align each column of a list of rows (lists of strings/None) independently; returns new rows."""
    if not cols:
        return cols
    T = list(zip(*cols))
    return [list(r) for r in zip(*[align(list(c)) for c in T])]


def colgroups_all(mats):
    """align the columns of several row blocks together (one alignment for the whole table)"""
    flat = colgroups([r for m in mats for r in m])
    out, k = [], 0
    for m in mats:
        out.append(flat[k:k + len(m)])
        k += len(m)
    return out


def sci_small(x, n=2, lim=1e-3):
    """n significant digits; numbers below lim in scientific notation"""
    if x is None:
        return None
    if x != 0 and abs(x) < lim:
        m, e = ("%.*e" % (n - 1, x)).split("e")
        return r"$%s\times10^{%d}$" % (m, int(e))
    return sig(x, n)


def mc(n, s, a="c"):
    return r"\multicolumn{%d}{%s}{%s}" % (n, a, s)


def hd(*lines):
    """multi-line header cell: a nested kernel tabular (makecell would load the array package, see write())"""
    return r"\begin{tabular}[b]{@{}c@{}}" + r"\\".join(lines) + r"\end{tabular}"


# ------------------------------------------------------------------------------------------------- Markdown
def read_md(path):
    txt = open(path, encoding="utf-8").read()
    try:                         # tables_map.md was written double-encoded (UTF-8 read as cp1252); undo it exactly
        fixed = txt.encode("cp1252").decode("utf-8")
        if "χ" in fixed or "̄" in fixed:
            txt = fixed
    except (UnicodeEncodeError, UnicodeDecodeError):
        pass
    return txt


def md_tables(path):
    """yield (heading, rows) for every Markdown table; cells split on unescaped '|' only."""
    lines = read_md(path).splitlines()
    head, i = "", 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("#") or (l.startswith("**") and l.rstrip().endswith("**")):
            head = l.strip("#* ").strip()
        if l.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s\-:|]+\|$", lines[i + 1].strip()):
            rows, j = [], i
            while j < len(lines) and lines[j].startswith("|"):
                if j != i + 1:
                    cells = re.split(r"(?<!\\)\|", lines[j].strip()[1:-1])
                    rows.append([c.strip() for c in cells])
                j += 1
            yield head, rows
            i = j
            continue
        i += 1


def md_table(path, start):
    for h, rows in md_tables(path):
        if h.startswith(start):
            return rows
    raise KeyError(start)


