"""SM tables of the exploratory bias analysis. Input: phase3/full_runs/bias_law/out/results.json. Output: sm_tables/bias_*.tex."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(os.path.join(HERE, '..', '..', 'phase3', 'full_runs', 'bias_law', 'out', 'results.json')))
HEAD = '% generated by figures/make_sm_bias_law.py from phase3/full_runs/bias_law/out/results.json -- do not edit\n'


def f(x):
    return f'{x:.2f}'


# 2026-11-10: rows holding only digits collapsed to their glyph height in REVTeX's longtable and overlapped (Table S27,
# baseline gap 0.63 x the font size; check_overlap.py). Every row now starts with an invisible strut one line high.
STRUT = r'\rule[-3pt]{0pt}{11.5pt}'


def strut(lines):
    return [STRUT + ' ' + l if (l.endswith('\\') and '&' in l) else l for l in lines]


L = [HEAD, r'{\footnotesize\setlength{\tabcolsep}{5pt}\renewcommand{\arraystretch}{1.2}', r'\begin{longtable}{llcccc}',
     r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule',
     r'$n$ & $J_z$ & $\delta e$ & as generated & truth at $n=19$ & corrected \\', r'\midrule']
for n in ('57', '115'):
    for r in R['n19_curve'][n]['rows']:
        L.append(f"{n} & {r['J']:.1f} & {r['de']:.5f} & {f(r['raw'])} & {f(r['small_truth'])} & {f(r['corrected'])} \\\\")
    L.append(r'\midrule')
L[-1] = r'\bottomrule'
L += [r'\end{longtable}}']
open(os.path.join(HERE, 'sm_tables', 'bias_rows.tex'), 'w', encoding='utf8').write('\n'.join(strut(L)) + '\n')

L = [HEAD, r'{\footnotesize\setlength{\tabcolsep}{5pt}\renewcommand{\arraystretch}{1.2}', r'\begin{longtable}{lcccc}',
     r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule',
     r'model and label & size & as generated & corrected & small-system truth \\', r'\midrule']
for r in R['other_models']['rows']:
    name = r['model'].replace('Jz=', '$J_z=').replace('J2=', '$J_2=').replace('C_zz', r'$\bar C_{zz}$').replace('m_s^2', '$m_s^2$').replace('J1-J2', r'$J_1$--$J_2$')
    parts = name.split()
    out = []
    for w in parts:
        if w.startswith('$J_z=') or w.startswith('$J_2='):
            w += '$'
        out.append(w)
    name = ' '.join(out).replace('seed=', 'seed ')
    L.append(f"{name} & {r['src']} & {f(r['raw'])} & {f(r['corrected'])} & {f(r['small_truth'])} \\\\")
L += [r'\bottomrule', r'\end{longtable}}']
open(os.path.join(HERE, 'sm_tables', 'bias_other.tex'), 'w', encoding='utf8').write('\n'.join(strut(L)) + '\n')
print('ok')
