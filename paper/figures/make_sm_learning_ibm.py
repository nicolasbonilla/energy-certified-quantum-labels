"""Supplemental table of the realistic learning test on the heavy-hex model (final-fix pass, 2026-11-04).
Reads phase3/full_runs/learning_ibm/out/results.json (read-only) and writes sm_tables/learn_ibm.tex (longtable, same
format as the other generated SM tables).  python make_sm_learning_ibm.py"""
import json
import os

import common as C

F = os.path.join(C.ROOT, "phase3", "full_runs", "learning_ibm", "out", "results.json")
OUT = os.path.join(C.HERE, "sm_tables", "learn_ibm.tex")
NAMES = {"poly3_invJ": "cubic in $1/J_z$", "mlp_pilot3": "small perceptron",
         "ibm_arch1": "per-site perceptron stack (dataset paper)", "null_nn": "nearest-neighbour null"}


def f2(x):
    return "%.2f" % x


def rng(a):
    return "%.2f--%.2f" % (a[0], a[1]) if abs(a[1] - a[0]) > 5e-3 else "%.2f" % a[0]


def main():
    R = json.load(open(F, encoding="utf-8"))
    L = [r"% generated by figures/make_sm_learning_ibm.py from phase3/full_runs/learning_ibm/out/results.json -- do not edit",
         r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.25}",
         r"\begin{longtable}{llcccccc}",
         r"\caption{\SMcap}\label{\SMlab}\\",
         r"\toprule",
         r" & & \multicolumn{4}{c}{trained on emulated labels} & \multicolumn{2}{c}{trained on DMRG labels} \\ "
         r"\cmidrule(lr){3-6}\cmidrule(l){7-8}",
         r"$n$ & test & \begin{tabular}[b]{@{}c@{}}sites: covers\\new emulated\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}sites: covers\\truth\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}$m_s$: covers\\truth\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}$m_s$: width, miss\\(units of $\tau$)\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}sites: covers\\truth\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}$m_s$: miss\\(units of $\tau$)\end{tabular} \\",
         r"\midrule"]
    for m in ("poly3_invJ", "mlp_pilot3", "ibm_arch1", "null_nn"):
        L.append(r"\multicolumn{8}{@{}l}{\textbf{%s}}\\" % NAMES[m])
        for n in ("57", "115"):
            M = R["sizes"][n]["models"].get(m)
            if not M:
                continue
            for key, lab in (("indist", "training range"), ("ood", "1.1--1.4")):
                if key + "_emulated" not in M:
                    continue
                e = M[key + "_emulated"]["summary"]
                c = M[key + "_exact_control"]["summary"]
                L.append("%s & %s & %s & %s & %s & %s; %s & %s & %s \\\\" % (
                    n, lab, f2(e["covZ_emu"]), f2(e["covZ_truth"]), f2(e["covM_truth"]),
                    f2(e["widthM_tau_median"]), rng(e["miss_ms_over_tau_range"]), f2(c["covZ_truth"]),
                    rng(c["miss_ms_over_tau_range"])))
    L += [r"\bottomrule", r"\end{longtable}}"]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
