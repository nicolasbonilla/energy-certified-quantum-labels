"""Supplemental table: Proposition 2(a)/(b) for the cubic model on the heavy-hex labels (third-reading pass,
2026-11-04). Reads phase3/full_runs/learning_ibm/out/prop2_cubic.json (read-only) and writes
sm_tables/learn_prop2.tex (longtable, same format as the other generated SM tables).  python make_sm_learning_prop2.py"""
import json
import os

import common as C

F = os.path.join(C.ROOT, "phase3", "full_runs", "learning_ibm", "out", "prop2_cubic.json")
OUT = os.path.join(C.HERE, "sm_tables", "learn_prop2.tex")


def pair(lo, hi, ind=False, fmt="%.2f"):
    m = max(lo, hi)
    f = "%.0f" if m >= 100 else ("%.1f" if m >= 10 else fmt)
    s = (f % lo) + "--" + (f % hi)
    return s + ("$^\\dagger$" if ind else "")


def main():
    P = json.load(open(F, encoding="utf-8"))
    L = [r"% generated by figures/make_sm_learning_prop2.py from phase3/full_runs/learning_ibm/out/prop2_cubic.json -- do not edit",
         r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.2}",
         r"\begin{longtable}{llccccc}",
         r"\caption{\SMcap}\label{\SMlab}\\",
         r"\toprule",
         r"$n$ & $J_z$ & \begin{tabular}[b]{@{}c@{}}label's energy\\interval, $w/\tau$\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}band (a)\\$W(x)/\tau$\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}interval (b)\\width $2q/\tau$\end{tabular} & "
         r"\begin{tabular}[b]{@{}c@{}}miss of $m_s$\\(units of $\tau$)\end{tabular} & rule (c) \\",
         r"\midrule"]
    for n in ("57", "115"):
        S = P["sizes"][n]
        rows = S["indist"] + S["ood"]
        for r in rows:
            J = r["Jz"]
            iv = S["intervals"].get("%s" % J) or S["intervals"].get("%.1f" % J)
            w = pair(iv["w_in_tau"], iv["w_out_tau"]) if iv else "no map row"
            tag = "" if J >= 1.6 else " (test)"
            L.append("%s & %.1f%s & %s & %s & %s & %.2f & %s \\\\" % (
                n, J, tag, w, pair(r["W_lo_tau"], r["W_hi_tau"], r["W_indicative"]),
                pair(r["width_b_lo_tau"], r["width_b_hi_tau"], r["q_indicative"]), r["miss_over_tau"],
                "answer" if r["rule_c"] == "ANSWER" else "abstain"))
        if n == "57":
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{longtable}}"]
    with open(OUT, "w", encoding="utf-8") as fo:
        fo.write("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
