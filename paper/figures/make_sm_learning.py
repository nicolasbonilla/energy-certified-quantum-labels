"""SM tables of the learning run (Track-1 integration pass, 2026-11-04).  Laptop only; reads, never writes, the result
folder phase3/full_runs/learning/analysis/ (learn_M1_D_O.json, learn_M2_D_O.json).

Writes sm_tables/learn_cov_M1.tex, sm_tables/learn_cov_M2.tex (coverage of the true labels, of the generator's own
labels, widths) and sm_tables/learn_abst.tex (abstention rules at tau = 0.08).  Every cell is a JSON field rounded
to the printed precision; nothing is typed by hand.
"""
import json
import os

import common as C

AN = os.path.join(C.ROOT, "phase3", "full_runs", "learning", "analysis")
OUT = os.path.join(C.HERE, "sm_tables")
SETS = [("exact", "exact"), ("gen1", r"realistic, $10^{-3}$"), ("gen5", r"realistic, $5\times10^{-3}$"),
        ("advL1", r"shifted ($-$), $10^{-3}$"), ("advL5", r"shifted ($-$), $5\times10^{-3}$"),
        ("advM5", r"shifted ($+$), $5\times10^{-3}$")]
CLS = [("avg", "averages"), ("nn", "bonds"), ("diag", "diagonal pairs")]
HEAD = ("% generated by figures/make_sm_learning.py from phase3/full_runs/learning/analysis/learn_XMX_D_O.json "
        "-- do not edit\n")


def f3(x):
    return "--" if x is None else "%.3f" % x


def cov_table(M):
    r = json.load(open(os.path.join(AN, "learn_%s_D_O.json" % M), encoding="utf-8"))["coverage"]
    L = [HEAD.replace("XMX", M),
         r"{\footnotesize\setlength{\tabcolsep}{4.5pt}\renewcommand{\arraystretch}{1.15}",
         r"\begin{longtable}{llcccccccc}",
         r"\caption{\SMcap}\label{\SMlab}\\",
         r"\toprule",
         r" & & \multicolumn{2}{c}{SC} & NC & ENS & CSC & CSC/SC & SC & CSC \\ \cmidrule(lr){3-4}",
         r"labels & class & truth & own & truth & truth & truth & width & OOD & OOD \\",
         r"\midrule"]
    for key, nm in SETS:
        c = r[key]
        for k, (cl, cn) in enumerate(CLS):
            sc, cs = c["SC"][cl], c["CSC"][cl]
            ratio = cs["wid_id"] / sc["wid_id"] if key != "exact" else None
            row = [nm if k == 0 else "", cn, f3(sc["covT_id"]), f3(sc["covO_id"]), f3(c["NC"][cl]["covT_id"]),
                   f3(c["ENS"][cl]["covT_id"]), f3(cs["covT_id"]), "--" if ratio is None else "%.2f" % ratio,
                   f3(sc["covT_ood"]), f3(cs["covT_ood"])]
            L.append(" & ".join(row) + r" \\")
        L.append(r"\addlinespace[2pt]")
    L += [r"\bottomrule", r"\end{longtable}}", ""]
    open(os.path.join(OUT, "learn_cov_%s.tex" % M), "w", encoding="utf-8").write("\n".join(L))


def abst_table():
    rows = [("M1", "gen5", "avg", "id"), ("M1", "advL5", "avg", "id"), ("M1", "gen5", "avg", "ood"),
            ("M1", "gen5", "nn", "id"), ("M1", "gen1", "avg", "id"), ("M1", "gen1", "avg", "ood"),
            ("M2", "gen5", "avg", "id"), ("M2", "advL5", "avg", "id"), ("M2", "gen5", "avg", "ood"),
            ("M2", "gen1", "avg", "id"), ("M2", "gen1", "avg", "ood")]
    # "CB" = the declared truth-certified rule: answer iff the CB interval is at most tau wide, predict its MIDPOINT
    # (JSON key CB_mid; the key CB predicts f instead and is not the declared rule)
    rules = ["BAND", "CB_mid", "CSC", "NC", "SC", "ENS"]
    R = {M: json.load(open(os.path.join(AN, "learn_%s_D_O.json" % M), encoding="utf-8"))["abstention"]
         for M in ("M1", "M2")}
    L = [HEAD.replace("XMX", "M1/M2"),
         r"{\scriptsize\setlength{\tabcolsep}{2.4pt}\renewcommand{\arraystretch}{1.15}",
         r"\begin{longtable}{llll" + "c" * len(rules) + "}",
         r"\caption{\SMcap}\label{\SMlab}\\",
         r"\toprule",
         "learner & labels & class & inputs & " + " & ".join(r.replace("CB_mid", "CB") for r in rules) + r" \\",
         r"\midrule"]
    names = {"gen5": r"realistic, $5\times10^{-3}$", "advL5": r"shifted ($-$), $5\times10^{-3}$",
             "gen1": r"realistic, $10^{-3}$"}
    for M, ls, cl, dom in rows:
        rr = R[M]["%s|%s|%s|0.08" % (ls, cl, dom)]["rule"]
        cells = []
        for ru in rules:
            x = rr.get(ru)
            if x is None:
                cells.append("--")
            elif x["answer_rate"] == 0:
                cells.append("0.000/--")
            else:
                cells.append("%.3f/%.3f" % (x["answer_rate"], x["exceed_given_answer"]))
        L.append(" & ".join([M, names[ls], {"avg": "averages", "nn": "bonds"}[cl],
                             {"id": "in", "ood": "shifted"}[dom]] + cells) + r" \\")
    L += [r"\bottomrule", r"\end{longtable}}", ""]
    open(os.path.join(OUT, "learn_abst.tex"), "w", encoding="utf-8").write("\n".join(L))


if __name__ == "__main__":
    cov_table("M1")
    cov_table("M2")
    abst_table()
    print("wrote sm_tables/learn_cov_M1.tex, learn_cov_M2.tex, learn_abst.tex")
