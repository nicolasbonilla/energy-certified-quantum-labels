for c in ('32', '64'):
    L.append(f"DMRG on the target, bond dimension {c} & outside the rule & {B['Jz']['1.6']['low_chi_mean'][c]:.4f} & {B['Jz']['2.5']['low_chi_mean'][c]:.5f} \\\\")
