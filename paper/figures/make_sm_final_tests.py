NAMES = [('label', 'label as generated', 'quantum'), ('q_top', 'label with correction (primary)', 'quantum'),
         ('q_top_noref', 'same, ground energy without target-size reference', 'quantum'),
         ('q_kry', 'correction trained on the first stage at $n=19$', 'quantum'), ('q_kry_noref', 'same, without reference', 'quantum'),
         ('reg', 'regression on local couplings', 'classical'), ('open13', 'open cluster, 13 sites', 'classical'),
         ('open19', 'open cluster, 19 sites', 'classical'), ('stack', 'stack on 13-site clusters', 'classical'),
         ('emb13', 'embedded cluster, 13 sites', 'classical'), ('emb19', 'embedded cluster, 19 sites (best classical)', 'classical')]
L = [HEAD, OPEN % '5', r'\begin{longtable}{llcc}', r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule', r'estimate & uses & $J_z=1.6$ & $J_z=2.5$ \\', r'\midrule']
for k, name, use in NAMES:
    L.append(f"{name} & {use} & {g(B['Jz']['1.6']['mean'][k])} & {g(B['Jz']['2.5']['mean'][k])} \\\\")
