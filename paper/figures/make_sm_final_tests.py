L = [HEAD, OPEN % '5', r'\begin{longtable}{ccccc}', r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule',
     r'instance & \multicolumn{2}{c}{$J_z=1.6$} & \multicolumn{2}{c}{$J_z=2.5$} \\', r' & best classical & label with correction & best classical & label with correction \\', r'\midrule']
for i in range(6):
    a, b = B['Jz']['1.6']['per_instance'], B['Jz']['2.5']['per_instance']
    L.append(f"{i} & {f(a['emb19'][i], 3)} & {f(a['q_top'][i], 3)} & {f(b['emb19'][i], 3)} & {f(b['q_top'][i], 3)} \\\\")
