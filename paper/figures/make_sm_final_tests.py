# proved intervals. End points of a proved interval are rounded outward (LECCIONES 7b, 2026-11-10): lower end down,
# upper end up, from the exact rationals; the declared job at Jz = 6.0 (C3, 2026-11-10) comes from c3b_20261110/test_c3b.json.
from fractions import Fraction
import math
C3 = json.load(open(os.path.join(AN, 'c3b_20261110', 'test_c3b.json'), encoding='utf8'))['C3']


def out5(q):
    lo, hi = Fraction(q['lo_exact']), Fraction(q['hi_exact'])
    return f"{math.floor(lo * 10**5) / 10**5:.5f}", f"{math.ceil(hi * 10**5) / 10**5:.5f}"


L = [HEAD, OPEN % '5', r'\begin{longtable}{lcccc}', r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule', r'state & label & proved interval & width & width$/\tau$ \\', r'\midrule']
for src, v, name in ((C['C1'], 'rec', 'device, $J_z=4.0$, with recovery'), (C['C1'], 'ps', 'device, $J_z=4.0$, postselected'),
                     (C3, 'rec', 'device, $J_z=6.0$, with recovery'), (C3, 'ps', 'device, $J_z=6.0$, postselected')):
    r = src[v]
    for o, lab, sym in (('m_s', 'm_s_label', r'$m_s$'), ('Czz_bar', 'Czz_bar_label', r'$\bar C_{zz}$')):
        q = r[o]
        lo, hi = out5(q)
        L.append(f"{name}, {sym} & ${r[lab]:.5f}$ & $[{lo},\\,{hi}]$ & {q['width']:.4f} & {q['w_over_tau']:.2f} \\\\")   # label in math: a true minus sign
L += [r'\bottomrule', r'\end{longtable}}']
write('ft_c.tex', L)

