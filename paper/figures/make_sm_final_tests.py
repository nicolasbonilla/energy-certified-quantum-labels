"""SM tables of the declared tests. Input: phase3/full_runs/final_tests/analysis/*.json. Output: sm_tables/ft_*.tex."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
AN = os.path.join(HERE, '..', '..', 'phase3', 'full_runs', 'final_tests', 'analysis')
A = json.load(open(os.path.join(AN, 'test_a.json'), encoding='utf8'))
B = json.load(open(os.path.join(AN, 'test_b.json'), encoding='utf8'))
C = json.load(open(os.path.join(AN, 'test_c.json'), encoding='utf8'))
X = json.load(open(os.path.join(AN, 'test_c_extra.json'), encoding='utf8'))
HEAD = '% generated by figures/make_sm_final_tests.py from phase3/full_runs/final_tests/analysis/ -- do not edit\n'
OPEN = r'{\footnotesize\setlength{\tabcolsep}{%spt}\renewcommand{\arraystretch}{1.2}'


STRUT = r'\rule[-3pt]{0pt}{11.5pt}'   # absolute: inside these longtables \baselineskip itself was found too small


def write(name, lines):
    # 2026-11-10: in REVTeX's longtable, rows holding only digits were set by their glyph height alone and overlapped
    # (Tables S29-S31, baseline gap 0.63 x the font size; found by check_overlap.py). Every row now starts with an
    # invisible strut one line high, so rows keep a normal height whatever they contain.
    out = [STRUT + ' ' + l if (l.endswith(r'\\') and '&' in l) else l for l in lines]
    open(os.path.join(HERE, 'sm_tables', name), 'w', encoding='utf8').write('\n'.join(out) + '\n')


def f(x, d=2):
    return f'{x:.{d}f}'


def g(x):
    return f'{x:.3f}' if x < 0.1 else f'{x:.2f}'


# blind test
L = [HEAD, OPEN % '3', r'\begin{longtable}{llcccccccc}', r'\caption{\SMcap}\label{\SMlab}\\', r'\toprule',
     r'$n$ & $J_z$ & $\delta e$ & as generated & curve & ratio & chord & truth at $n=19$ & $a+b/n$ & $a+b/\sqrt n$ \\', r'\midrule']
for r in A['rows']:
    extra = f"{g(r['miss_a_b_over_n'])} & {g(r['miss_a_b_over_sqrt_n'])}" if r['n'] == 115 else '-- & --'
    L.append(f"{r['n']} & {r['J']:.1f} & {r['de']:.5f} & {f(r['raw'])} & {g(r['miss_curve19'])} & {f(r['ratio'], 3)} & {g(r['miss_chord'])} & "
             f"{f(r['small_truth'])} & {extra} \\\\")
L += [r'\bottomrule', r'\end{longtable}}']
write('ft_a.tex', L)

