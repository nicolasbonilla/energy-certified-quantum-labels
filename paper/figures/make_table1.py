"""Table 1 body (LaTeX rows) of the main text, generated from the certification map; no number is typed by hand.

  python make_table1.py      -> table1_rows.tex (next to this file), \\input by main.tex

Columns (reading 1 of the digitized energies; tau = 0.06 |O_GS|):
  w_in(E_lo)/tau at Jz = 1.2 (OOD, conditional floor) and at Jz = 1.6: rigorous side, "not certified" if >= 1;
  J* central (strict) and number of certified training points out of 45 (summary_map.json jstar[*_r1]);
  w_out(E_dig)/tau at the largest computed Jz (6.0, or 4.0 where only that point exists): certificate side;
  range of delta e*_law / delta e* over the rows with Jz >= 2.0 (rows[*].law_ratio_out).
Source: phase3/full_runs/map/laptop_analysis/summary_map.json.
"""
import os

import common as C

NAMES = {"m_s": r"$m_s$", "Czz_bar": r"$\bar C_{zz}$", "C2_bar": r"$\bar C_{2}$", "Z_bulk": r"$Z_{\rm bulk}$",
         "Z_boundary": r"$Z_{\rm bdry}$", "Czz_edge": r"$C_{zz}^{\rm edge}$", "Z_loop": r"$Z_{\rm loop}$"}
ORDER = [(57, k) for k in NAMES] + [(115, "m_s"), (115, "Czz_bar"), (115, "C2_bar"), (115, "Z_bulk")]


def f2(x):
    return "%.2f" % x if x < 10 else "%.1f" % x


def main():
    S = C.map_summary()
    lines = []
    for n, lab in ORDER:
        rows = sorted((r for r in S["rows"] if r["n"] == n and r["label"] == lab), key=lambda r: r["Jz"])
        by = {round(r["Jz"], 1): r for r in rows}
        c12 = f2(by[1.2]["at_lo"]["w_in"] / by[1.2]["tau"]) if 1.2 in by else "--"
        c16 = f2(by[1.6]["at_lo"]["w_in"] / by[1.6]["tau"]) if 1.6 in by else "--"
        js = S["jstar"].get("%d_%s_r1" % (n, lab))
        if js:
            jc, jst = js["J_star_central"], js["J_star_strict"]
            jstar = ("%.1f" % jc if jc else "none") + " (" + ("%.1f" % jst if jst else "none") + ")"
            ncert = "%d" % js["n_certified_central"]
        else:
            jstar, ncert = "--", "--"
        last = rows[-1]
        wl = f2(last["at_dig"]["w_out"] / last["tau"]) + ("" if abs(last["Jz"] - 6.0) < 1e-9 else r"$^{a}$")
        lr = [r["law_ratio_out"] for r in rows if r["Jz"] >= 2.0 and r.get("law_ratio_out")]
        law = "%.2f--%.2f" % (min(lr), max(lr)) if lr else "--"
        lines.append("%s & %d & %s & %s & %s & %s & %s & %s \\\\" % (NAMES[lab], n, c12, c16, jstar, ncert, wl, law))
        if (n, lab) == (57, "Z_loop"):
            lines.append("\\hline")
    out = os.path.join(C.HERE, "table1_rows.tex")
    with open(out, "w", encoding="utf-8") as fo:
        fo.write("% generated by figures/make_table1.py from phase3/full_runs/map/laptop_analysis/summary_map.json\n")
        fo.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
