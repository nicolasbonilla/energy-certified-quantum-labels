"""make_rdtest.py -- tables of Supplemental Sec. S18 (tests of the bias on the public labels).

  python -B -I make_rdtest.py            (writes rdtest_*.tex next to this file; reads one JSON file, writes nothing else)

Input (read only): phase3/full_runs/real_data/out/predict_real.json, the output of the analysis code that was fixed in
writing before it ran (run_predict.py) together with the independent recomputation and the lines added afterwards.
Every number printed in the tables is read from that file; nothing is recomputed here except sums of stored counts and
the conversion of a stored fraction F and a stored number of pairs into a number of pairs (round((1 - F) * pairs)).

Output: rdtest_sign.tex, rdtest_trend.tex, rdtest_d.tex, rdtest_curve_n57.tex, rdtest_curve_n115.tex,
        rdtest_summary.tex. Each is read by an input command of parts/s18_public_tests.tex, which defines the caption
        (SMcap) and the label (SMlab) first.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "phase3", "full_runs", "real_data", "out", "predict_real.json")
HEAD = ("% generated by figures/sm_tables/make_rdtest.py from phase3/full_runs/real_data/out/predict_real.json"
        " -- do not edit\n")
STRUT = r"\rule[-3pt]{0pt}{11.5pt}"          # every row one line high (see make_sm_bias_law.py, 2026-11-10)
FAMILIES = [("sites", "sites"), ("edges", "edges"), ("second_neighbours", "second neighbours"), ("loops", "loops")]
BAND = (0.75, 1.3)
EOL = " " + chr(92) + chr(92)                # the two backslashes that end a table row


def strut(lines):
    return [STRUT + " " + l if (l.endswith(EOL.strip()) and "&" in l) else l for l in lines]


def table(cols, header, rows, tabcolsep=3):
    """a longtable whose header repeats on every page. header: one string or a list of lines (the cells of a header
    row, or a rule that starts with a backslash); rows: a list of strings (cells) or of rules."""
    head = [header] if isinstance(header, str) else list(header)
    head = [h if h.startswith(chr(92)) else h + EOL for h in head]
    L = [HEAD, r"{\footnotesize\setlength{\tabcolsep}{%dpt}\renewcommand{\arraystretch}{1.2}" % tabcolsep,
         r"\begin{longtable}{%s}" % cols, r"\caption{\SMcap}\label{\SMlab}" + EOL.strip(), r"\toprule"]
    L += head + [r"\midrule", r"\endfirsthead", r"\toprule"] + head + [r"\midrule", r"\endhead"]
    for r in rows:
        L.append(r if r.startswith(chr(92)) else r + EOL)
    L += [r"\bottomrule", r"\end{longtable}}"]
    return "\n".join(strut(L)) + "\n"


def write(name, text):
    with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("written", name, "(%d lines)" % text.count("\n"))


def main():
    with open(SRC, encoding="utf-8") as f:
        R = json.load(f)
    S = R["sizes"]

    # ---- sign (declared tests P1-P3): one row per family and size
    rows = []
    tot_pairs = tot_bad = 0
    for n in ("57", "115"):
        for key, name in FAMILIES:
            b = S[n]["P1_P3"][key]
            bad = int(round((1.0 - b["F"]) * b["n_pairs"]))
            tot_pairs += b["n_pairs"]
            tot_bad += bad
            rows.append("%s & %s & %d & %d & %d & %.6f & %s & $%.4f$ & %.4f" % (
                n, name, b["n_items"], b["n_pairs"], bad, b["F"], "holds" if b["holds"] else "does not hold",
                b["t_min"], b["t_max"]))
        rows.append(r"\midrule")
    rows.append(r"both & all four & & %d & %d & & & &" % (tot_pairs, tot_bad))
    write("rdtest_sign.tex", table(
        "llccccccc",
        r"$n$ & family & labels & pairs & not over-ordered & $F$ & rule $F\ge0.95$ & smallest $t$ & greatest $t$", rows))

    # ---- trend (declared test P4): one row per family and size, m_s next to them (it decides nothing)
    rows = []
    for n in ("57", "115"):
        for key, name in FAMILIES + [("m_s", r"$m_s$ (no decision)")]:
            b = S[n]["P4"][key]
            rows.append("%s & %s & $%.4f$ & %s & %.3f & %.3f" % (
                n, name, b["spearman"], ("holds" if b["holds"] else "does not hold") if key != "m_s" else "--",
                b["D"]["1.1"], b["D_min"]))
        rows.append(r"\midrule")
    rows.pop()
    write("rdtest_trend.tex", table(
        "llcccc", r"$n$ & family & rank correlation of $D$ with $J_z$ & rule $\le-0.9$ & $D$ at $J_z=1.1$ & smallest $D$",
        rows, tabcolsep=5))

    # ---- D per coupling, four families and m_s, both sizes
    rows = []
    for J in S["57"]["couplings"]:
        k = "%.1f" % J
        cells = [k]
        for n in ("57", "115"):
            for key in ("sites", "edges", "second_neighbours", "loops", "m_s"):
                cells.append("%.3f" % S[n]["P4"][key]["D"][k])
        rows.append(" & ".join(cells))
    write("rdtest_d.tex", table(
        "l" + "c" * 10,
        [r" & \multicolumn{5}{c}{$n=57$} & \multicolumn{5}{c}{$n=115$}", r"\cmidrule(lr){2-6}\cmidrule(lr){7-11}",
         r"$J_z$ & sites & edges & 2nd nb. & loops & $m_s$ & sites & edges & 2nd nb. & loops & $m_s$"], rows))

    # ---- the curve (declared test P5), every coupling, one table per size
    for n in ("57", "115"):
        kept = set("%.1f" % x for x in S[n]["n19_comparison"]["kept"])
        rows = []
        for r in S[n]["P5"]["rows"]:
            k = "%.1f" % r["Jz"]
            ratio = "%.4f" % r["ratio"]
            outside = not (BAND[0] <= r["ratio"] <= BAND[1])
            if outside and r["decides_ratio"]:
                ratio = r"\textbf{%s}" % ratio
            elif outside:
                ratio = "(%s)" % ratio
            rows.append("%s & %.6f & %.6f & %.6f & %s & %s & %.3f & %.3f & %.3f & %.3f & %s" % (
                k, r["de"], r["Delta"], r["curve"], ratio, "yes" if r["decides_ratio"] else "--", r["raw_miss_tau"],
                r["miss_tau"], r["miss_chord_tau"], r["miss_n19_truth_tau"], "yes" if k in kept else "--"))
        write("rdtest_curve_n%s.tex" % n, table(
            "l" + "c" * 10,
            [r" & & & & & & \multicolumn{4}{c}{miss in units of $\tau$} & ", r"\cmidrule(lr){7-10}",
             r"$J_z$ & $\delta e$ & $\Delta m_s$ & curve & ratio & decides & as published & curve & chord & "
             r"19-site value & certified"], rows))

    # ---- means and greatest misses with the comparators
    rows = []
    for key, name in (("all", "all 50 (decides)"), ("training_45", r"45 training, $J_z\ge1.6$"),
                      ("test_1p1_1p4", r"4 test, $J_z=1.1$--$1.4$")):
        for n in ("57", "115"):
            b = S[n]["P5"][key]
            rows.append("%s & %s & %.3f & %.3f & %.3f & %.3f & %.3f & %.3f & %.3f & %.3f" % (
                name, n, b["mean_raw_miss_tau"], b["max_raw_miss_tau"], b["mean_miss_tau"], b["max_miss_tau"],
                b["mean_miss_chord_tau"], b["max_miss_chord_tau"], b["mean_miss_n19_truth_tau"],
                b["max_miss_n19_truth_tau"]))
        rows.append(r"\midrule")
    rows.pop()
    write("rdtest_summary.tex", table(
        "llcccccccc",
        [r" & & \multicolumn{2}{c}{as published} & \multicolumn{2}{c}{curve} & \multicolumn{2}{c}{chord} & "
         r"\multicolumn{2}{c}{19-site value}",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}",
         r"couplings & $n$ & mean & max. & mean & max. & mean & max. & mean & max."], rows))


if __name__ == "__main__":
    main()
