import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))           # the folder that holds phase3/ and paper/
RD = os.path.join(ROOT, "phase3", "full_runs", "real_data")
STRUT = r"\rule[-3pt]{0pt}{11.5pt} "
SETS = {"S": r"$\tau$", "S_3_4": r"$3\tau/4$", "S_1_2": r"$\tau/2$"}
MODN = {"M1": r"M1: line in $1/J_z$", "M2": r"M2: $1-a/J_z^2-b/J_z^4$", "M0": r"M0: control (cubic, all labels)"}
F1N = {"poly3_invJ": r"cubic in $1/J_z$ (primary)", "null_nn": "nearest-neighbour null", "mlp_pilot3": "small neural network",
       # R11 (hostile-B-02): the model is the dataset paper's "architecture 1", implemented by us, not its main architecture
       "ibm_arch1": r"the dataset paper's architecture~1, our implementation (declared for $n=57$, test range only)"}
# R11 (hostile-B-02): the same correction in the heading of the copied table of the study on emulated labels
EMU_HEAD = ("per-site perceptron stack (dataset paper)",
            "per-site perceptron stack (the dataset paper's architecture~1, our implementation)")


def rj(*p):
    with open(os.path.join(*p), encoding="utf-8") as f:
        return json.load(f)


def dn(x, d=2):
    return math.floor(x * 10 ** d + 1e-9) / 10 ** d


def up(x, d=2):
    return math.ceil(x * 10 ** d - 1e-9) / 10 ** d


def rng(a, d=2):
    """range rounded outward"""
    return "%.*f--%.*f" % (d, dn(a[0], d), d, up(a[1], d))


def write(name, lines, src):
    head_ = ["%% generated by figures/sm_tables/make_rdlearn.py from %s -- do not edit" % src]
    with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(head_ + lines) + "\n")
    print("wrote", name, "(%d lines)" % (len(lines) + 1))


def table(cols, header, rows, stretch="1.15", sep="4pt"):
    out = [r"{\footnotesize\setlength{\tabcolsep}{%s}\renewcommand{\arraystretch}{%s}" % (sep, stretch),
           r"\begin{longtable}{%s}" % cols, r"\caption{\SMcap}\label{\SMlab}\\", r"\toprule"]
    # first head (with the caption) and continuation head, as in the other tables of Secs. S17-S19. Under REVTeX a head
    # set with \endhead persists into later longtables that set none, so every table here sets its own.
    out += [STRUT + h for h in header] + [r"\midrule", r"\endfirsthead", r"\toprule"]
    out += [STRUT + h for h in header] + [r"\midrule", r"\endhead"]
    for r in rows:
        out.append(r if r.startswith("\\midrule") or r.startswith("\\multicolumn") else STRUT + r)
    out += [r"\bottomrule", r"\end{longtable}}"]
    return out


def cell2(a, b):
    return r"\begin{tabular}[b]{@{}c@{}}%s\\%s\end{tabular}" % (a, b)


def head(ncol, text):
    return r"\multicolumn{%d}{@{}l}{\rule[-3pt]{0pt}{11.5pt}\textbf{%s}}\\" % (ncol, text)


# ---------------------------------------------------------------------------------------------- the nested sets
def t_sets(L, E):
    rows = []
    for n in ("57", "115"):
        ic = L["independent_check"]["sizes"][n]["f3"]
        sp = L["summary"][n]["f3"]["S_p"]
        for k in ("S", "S_3_4", "S_1_2"):
            t = ic[k]
            rows.append("%s & declared & %s%s & %d & %.1f--%.1f & %s & %.3f & %s \\\\" % (
                n, SETS[k], " (primary)" if (n == "57" and k == sp) else "", t["size"], t["range"][0], t["range"][1],
                rng(t["exact_width_tau"], 3), up(t["label_miss_tau_max"], 3), rng(t["truth_change_over_tau"], 3)))
        rows.append(r"\midrule")
    for k in ("S", "S_3_4", "S_1_2"):
        t = E["sizes"]["115"]["sets"][k]
        rows.append("115 & extended & %s & %d & %.1f--%.1f & %s & %.3f & %s \\\\" % (
            SETS[k], t["size"], t["range"][0], t["range"][1], rng(t["exact_width_tau_range"], 3),
            up(t["greatest_label_miss_tau"], 3), rng(t["truth_change_over_tau"], 3)))
    hdr = [r"$n$ & certificates & " + cell2("labels", "certified to") + r" & couplings & $J_z$ & "
           + cell2("exact interval", r"width ($\tau$)") + " & " + cell2("greatest miss", r"of a label ($\tau$)") + " & "
           + cell2("change of the", r"true $m_s$ ($\tau$)") + r" \\"]
    write("rdlearn_sets.tex", table("llllcccc", hdr, rows),
          "phase3/full_runs/real_data/out/learn_real.json (independent_check.sizes.<n>.f3) and e1/learn_e1/summary_e1.json")


# ---------------------------------------------------------------------------------------------- (f1) every model
def t_f1(L):
    """Rows that the declared run left empty are printed as 'not computed (cost)'. To add a piece computed later
    (the neural models: phase3/full_runs/real_data/f1_neural/), put a file rdlearn_f1_extra.json next to this script:
    {"<n>|<model>|<real or control>|<test or ind>": {"n":, "truth_covered":, "label_covered":, "site_truth":,
    "site_label":, "width_tau": [lo, hi], "miss_tau": [lo, hi], "n_miss_above_tau":}, ...} with the field meanings of
    learn_real.json summary.<n>.models; model keys: poly3_invJ, null_nn, mlp_pilot3, ibm_arch1. The file is read if
    it exists and its rows replace the 'not computed' rows; name its source file in the caption of the table."""
    extra_path = os.path.join(HERE, "rdlearn_f1_extra.json")
    extra = rj(extra_path) if os.path.exists(extra_path) else {}
    rows = []
    for m in ("poly3_invJ", "null_nn", "mlp_pilot3", "ibm_arch1"):
        rows.append(head(9, F1N[m]))
        for n in ("57", "115"):
            M = L["summary"][n]["models"]
            for lab, labn in (("real", "public"), ("control", "DMRG")):
                for rg, rgn in (("test", "test"), ("ind", "training")):
                    if m == "ibm_arch1" and (n != "57" or rg != "test"):
                        continue
                    d = (M.get(m) or {}).get(lab, {}).get(rg) if M.get(m) else None
                    d = d or extra.get("%s|%s|%s|%s" % (n, m, lab, rg))
                    if d is None:
                        rows.append("%s & %s & %s & \\multicolumn{6}{c}{not computed (cost)} \\\\" % (n, labn, rgn))
                        continue
                    lab_cov = ("%d of %d" % (d["label_covered"], d["n"])) if lab == "real" else "--"
                    site = ("%.3f / %.3f" % (d["site_label"], d["site_truth"])) if lab == "real" else ("-- / %.3f" % d["site_truth"])
                    rows.append("%s & %s & %s & %s & %d of %d & %s & %s & %s & %d of %d \\\\" % (
                        n, labn, rgn, lab_cov, d["truth_covered"], d["n"], site, rng(d["width_tau"], 3),
                        rng(d["miss_tau"], 2), d["n_miss_above_tau"], d["n"]))
    hdr = [r"$n$ & labels & range & " + cell2("held-out", "labels inside") + " & " + cell2("truth", "inside") + " & "
           + cell2("sites:", "labels / truth") + " & " + cell2("width", r"$2q$ ($\tau$)") + " & "
           + cell2("miss of the", r"prediction ($\tau$)") + " & " + cell2("misses", r"above $\tau$") + r" \\"]
    write("rdlearn_f1.tex", table("lllcccccc", hdr, rows),
          "phase3/full_runs/real_data/out/learn_real.json (summary.<n>.models)")


# ---------------------------------------------------------------------------------------------- per coupling
def t_couplings(L, S, SE, n):
    R = L["sealed"]["results_cheap"]["sizes"][n]["models"]["poly3_invJ"]
    P = L["sealed"]["prop2_cubic"]["sizes"][n]
    F2 = L["sealed"]["f2_floor"]["sizes"][n]
    iv, ive = S["sizes"][n]["intervals"], SE["sizes"][n]["intervals"]
    und = set(round(x, 1) for x in L["summary"][n]["prop2"]["undecided"])
    rows = []
    for key, tag in (("ood", "test"), ("indist", "train")):
        rr = {round(r["Jz"], 1): r for r in R[key + "_emulated"]["rows"]}
        for p in P[key]:
            J = round(p["Jz"], 1); r = rr[J]; k = "%.1f" % J
            tau = 0.06 * abs(r["m_s_truth"])
            fl = F2["floor_over_tau"][k] if tag == "test" else F2["in_distribution_held_out"][k]["floor_over_tau"]
            ex = iv[k]["exact"]; ex1 = ive[k]["exact"]
            rows.append("%s & %s & %.2f & %.2f & %.3f & %s / %s & %s%s & %.2f & %.2f & %s & %s \\\\" % (
                k, tag, abs(r["bias_ms_label"]) / tau, r["miss_ms_over_tau"], r["widthM_tau"],
                "yes" if r["covM_truth"] else "no", "yes" if r["covM_emu"] else "no",
                ("%.2f" % dn(p["W_lo_tau"])) if p["W_lo_tau"] < 100 else ("%.0f" % math.floor(p["W_lo_tau"])),
                r"$^{\ast}$" if J in und else "", dn(p["width_b_lo_tau"]), dn(fl),
                ("%.3f" % up(ex["width_over_tau"], 3)) if ex else "--", ("%.3f" % up(ex1["width_over_tau"], 3)) if ex1 else "--"))
        if tag == "test":
            a = L["summary"][n]["apart"]["1.5"]
            rows.append("1.5 & apart & -- & %.2f & %.3f & %s / -- & -- & %.2f & %.2f & -- & -- \\\\" % (
                a["miss_tau"], 2 * a["standard_q"] / (0.06 * abs(a["truth"])), "yes" if a["covered_by_standard_interval"] else "no",
                dn(a["width_2b_lower_tau"]), dn(F2["floor_over_tau"]["1.5"])))
            rows.append(r"\midrule")
    hdr = [r"$J_z$ & range & " + cell2("miss of", "the label") + " & " + cell2("miss of", "the cubic") + " & " + cell2("standard", r"$2q$")
           + " & " + cell2("truth / label", "inside") + " & " + cell2(r"band (a),", "lower value") + " & "
           + cell2(r"$2q$ of (b),", "lower value") + " & " + cell2("floor (d),", "any learner") + " & "
           + cell2("exact", "interval") + " & " + cell2("with later", r"certificates") + r" \\"]
    write("rdlearn_couplings_n%s.tex" % n, table("llccccccccc", hdr, rows, stretch="1.05"),
          "phase3/full_runs/real_data/out/learn_real.json (sealed.results_cheap, sealed.prop2_cubic, sealed.f2_floor), out/S_sets.json, e1/learn_e1/S_sets_E1.json; n = %s" % n)


# ---------------------------------------------------------------------------------------------- (f3)
def f3_rows(n, cert, key, s, primary=False):
    title = "$n=%s$, %s, certified to %s%s" % (n, cert, SETS[key], " (primary)" if primary else "")
    if s["status"] != "RUN":
        return [head(6, title + ": %d couplings; not run (fewer than 15)" % s["size"])]
    T = s.get("couplings") or None
    lo, hi = (T[0], T[-1]) if T else s["range"]
    out = [head(6, title + ": %d couplings ($J_z=%.1f$--$%.1f$); %d / %d / %d" % (
        s["size"], lo, hi, s["n_train"], s["n_cal"], s["n_query"]))]
    for m in ("M1", "M2", "M0"):
        a = s["models"][m]
        nW = a.get("n_splits_W", int(round(a["frac_splits_W"] * a["n_splits"])))
        nC = a.get("n_pairs_C", int(round(a["frac_pairs_C"] * a["n_pairs"])))
        oc = s.get("outcome_M0", s.get("outcome_M0_control")) if m == "M0" else s["outcome_M1_M2"]
        out.append("%s & %d of %d & %d of %d & %.3f / %.3f / %.3f & %.3f & %s \\\\" % (
            MODN[m], nW, a["n_splits"], nC, a["n_pairs"], dn(a["width_tau_min"], 3), a["width_tau_median"],
            up(a["width_tau_max"], 3), up(a["largest_miss_tau"], 3), oc.lower()))
    return out


def t_f3(L, E3):
    rows = []
    for n in ("57", "115"):
        f3 = L["summary"][n]["f3"]
        for key in ("S", "S_3_4", "S_1_2"):
            rows += f3_rows(n, "declared", key, f3["sets"][key], primary=(n == "57" and key == f3["S_p"]))
        rows.append(r"\midrule")
    for key in ("S", "S_3_4", "S_1_2"):
        rows += f3_rows("115", "extended", key, E3["sizes"]["115"]["sets"][key])
    hdr = [r"model & " + cell2(r"(W): splits with $2q\le\tau$", "at every query") + " & " + cell2("(C): pairs with", "the truth inside")
           + " & " + cell2(r"$2q$ ($\tau$):", "min / median / max") + " & " + cell2("greatest", r"miss ($\tau$)") + r" & outcome \\"]
    write("rdlearn_f3.tex", table("lccccl", hdr, rows),
          "phase3/full_runs/real_data/out/learn_real.json (summary.<n>.f3) and e1/learn_e1/f3_constructive.json")


def t_f3_post(L):
    short = {"M1": "M1", "M2": "M2", "M0": "M0", "const_posthoc": "constant"}
    rows = []
    for n in ("57", "115"):
        ic = L["independent_check"]["sizes"][n]["f3"]; f3 = L["summary"][n]["f3"]["sets"]
        for key in ("S", "S_3_4", "S_1_2"):
            if ic[key].get("status") != "RUN":
                continue
            rows.append(head(12, "$n=%s$, labels certified to %s (%d couplings)" % (n, SETS[key], ic[key]["size"])))
            for m in ("M1", "M2", "M0", "const_posthoc"):
                a = ic[key]["models"][m]; sp = a["standard_score_posthoc"]
                b = f3[key]["models"].get(m)
                if b:
                    nl, ni = b["norm_literal"], b["norm_interval"]
                    wa = b["W_a_exact_tau_range"]
                    extra = "%s & %.1f & %s & %.1f & %.1f & %s" % (
                        rng([nl["width_tau_min"], nl["width_tau_max"]], 3), 100 * nl["frac_pairs_covered"],
                        rng([ni["width_tau_min"], ni["width_tau_max"]], 2), 100 * ni["frac_splits_all_widths_le_tau"],
                        100 * ni["frac_pairs_covered"], rng(wa, 2) if wa else "n.a.")
                else:
                    extra = "-- & -- & -- & -- & -- & --"
                rows.append("%s & %.1f & %.1f & %.1f & %.1f & %s & %s \\\\" % (
                    short[m], 100 * a["frac_splits_W"], 100 * a["frac_pairs_C"],
                    100 * sp["frac_splits_W"], 100 * sp["frac_pairs_C"], rng([sp["width_tau"][0], sp["width_tau"][2]], 3), extra))
        if n == "57":
            rows.append(r"\midrule")
    hdr = [r" & \multicolumn{2}{c}{interval score} & \multicolumn{3}{c}{standard score} & \multicolumn{2}{c}{normalized, literal} & "
           r"\multicolumn{3}{c}{normalized, worst case} & band (a) \\ "
           r"\cmidrule(lr){2-3}\cmidrule(lr){4-6}\cmidrule(lr){7-8}\cmidrule(lr){9-11}\cmidrule(l){12-12}",
           r"model & (W) & (C) & (W) & (C) & $2q$ ($\tau$) & $2q\sigma$ ($\tau$) & (C) & $2q\sigma$ ($\tau$) & (W) & (C) & $W(x)$ ($\tau$) \\"]
    write("rdlearn_f3_post.tex", table("lccccccccccc", hdr, rows, sep="3pt"),
          "phase3/full_runs/real_data/out/learn_real.json (independent_check.sizes.<n>.f3, summary.<n>.f3)")


def copy_emu():
    src = os.path.join(HERE, "learn_ibm.tex")
    txt = open(src, encoding="utf-8").read().split("\n", 1)[1]
    assert txt.count(EMU_HEAD[0]) == 1, "heading of the architecture-1 block not found once"
    txt = txt.replace(EMU_HEAD[0], EMU_HEAD[1])
    with open(os.path.join(HERE, "rdlearn_emu_standard.tex"), "w", encoding="utf-8", newline="\n") as f:
        f.write("% copy (all lines but this one) of the generated table of the study on emulated labels (its "
                "generator is named in the first line of the original file), with one block heading renamed (R11: "
                "the dataset paper's architecture 1, our implementation); copied by figures/sm_tables/make_rdlearn.py "
                "so that the file name read by the Supplement holds no company name -- do not edit\n" + txt)
    print("wrote rdlearn_emu_standard.tex (copy)")


def main():
    L = rj(RD, "out", "learn_real.json")
    S = rj(RD, "out", "S_sets.json")
    E = rj(RD, "e1", "learn_e1", "summary_e1.json")
    E3 = rj(RD, "e1", "learn_e1", "f3_constructive.json")
    SE = rj(RD, "e1", "learn_e1", "S_sets_E1.json")
    t_sets(L, E)
    t_f1(L)
    for n in ("57", "115"):
        t_couplings(L, S, SE, n)
    t_f3(L, E3)
    t_f3_post(L)
    copy_emu()


if __name__ == "__main__":
    main()
